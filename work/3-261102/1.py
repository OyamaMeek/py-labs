# 字符串切片与拼接
# 描述：给定一个字符串 s，请输出以下三个结果（每行一个）：
#
# ① 将 s 转换为小写后的字符串；
#
# ② s 中第 8 到第 13 个字符（下标从 0 开始，包含第 8 个，不含第 13 个，即 s[8:13]）；
#
# ③ 将 s 中所有的子串 "name" 替换为 "NAME" 后的字符串。
#
# 输入格式：一行，一个字符串 s（长度不超过 1000）。
#
# 输出格式：三行，依次为上述三个结果。
#
# 样例输入：
#
# Hello name World name Test
#
# 样例输出：
#
# hello name world name test
#
# me Wo
#
# Hello NAME World NAME Test
