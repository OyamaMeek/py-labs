# 字符串反转与回文判断
# 分值：15   预估时间：10分钟
# 描述：给定一个字符串（可能包含空格和标点符号），请输出它的反转字符串，并判断它是否为回文（忽略大小写和首尾空白后，正读和反读相同）。
# 如果是回文输出 `Yes`，否则输出 `No`。
# 输入格式：一行，一个字符串。
# 输出格式：两行，第一行为反转后的字符串，第二行为 `Yes` 或 `No`。
# 样例输入：Level
# 样例输出：leveL
# Yes
s = input()
s2 = s[::-1]
print(s2)
# 判断是否为回文，忽略大小写和首尾空白
if s.strip().lower() == s2.strip().lower():
    print("Yes")
else:
    print("No")
