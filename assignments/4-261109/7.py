# 猜数字游戏
# 分值：10   预估时间：10分钟
# 描述：程序预设一个整数 42，反复输入一个整数进行猜测，
# 直到猜中为止。每猜一次，如果偏小输出"小了"，偏大输出"大了"；
# 猜中时输出"猜对了"并结束程序。
# 输入保证第一个整数一定会有且最终必然会出现 42。
# 输入格式：若干行，每行一个整数。
# 输出格式：每行一条提示信息，直到出现"猜对了"。
# 样例输入：30
# 80
# 42
# 样例输出：小了
# 大了
# 猜对了
num=42
while True:
    guess=int(input())
    if guess<num:
        print("小了")
    elif guess>num:
        print("大了")
    else:
        print("猜对了")
        break