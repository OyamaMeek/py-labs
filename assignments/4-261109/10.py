# 九九乘法表
# 分值：10   预估时间：10分钟
# 描述：用嵌套循环输出九九乘法表的第 1~n 行。
# 第 i 行输出 i 个乘法式，格式为 a*b=结果，
# 用空格分隔（行列式顺序：scanf从1到i）。
# 输入格式：一行，一个正整数 n（1 ≤ n ≤ 9）。
# 输出格式：共 n 行，第 i 行有 i 个乘法式，用空格分隔。
# 样例输入：3
# 样例输出：1*1=1
# 1*2=2 2*2=4
# 1*3=3 2*3=6 3*3=9
n=int(input())
for i in range(1,n+1):
    for j in range(1,i+1):
        print(f"{j}*{i}={i*j}",end=" " if j<i else "")
    print()
