# 集合交并差运算
# 描述：给定两个整数集合 A 和 B，分别输出它们的交集、并集、差集
# （A-B）和对称差（对称差即只属于 A 或只属于 B 的元素）。每
# 行输出对应集合的元素，元素按从小到大排序，用空格分隔。
# 输入格式：第一行输入整数 n（0 ≤ n），第二行 n 个整数为集
# 合 A（可能含重复元素，转为集合后自动去重）；第三行输入整数 m（
# 0 ≤ m），第四行 m 个整数为集合 B（可能含重复元素，转为集
# 合后自动去重）。
# 输出格式：共四行，第一行为交集，第二行为并集，第三行为 A-B，第
# 四行为对称差。每行元素按升序用空格分隔，若集合为空输出空行。
# 样例输入：
# 4
# 1 2 3 4
# 3
# 3 4 5
# 样例输出：
# 3 4
# 1 2 3 4 5
# 1 2
# 1 2 5
